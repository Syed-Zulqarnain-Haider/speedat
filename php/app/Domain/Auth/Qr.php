<?php

declare(strict_types=1);

namespace Speedat\Domain\Auth;

/**
 * A QR encoder, written out because the Next.js app's `qrcode` package cannot
 * come with us: no Composer on the target host, and no build step to vendor one.
 *
 * SCOPE, DELIBERATELY SMALL. Byte mode, error correction level M, versions 1
 * to 10 - up to 213 bytes, where the longest otpauth:// URI this app can build
 * is about 140. Anything longer is refused rather than half-supported, and the
 * caller shows the "enter the key by hand" fallback that TotpSetup.tsx already
 * has. A QR that does not scan is worse than no QR, because the owner stands
 * there trying.
 *
 * WHAT IS IMPLEMENTED (ISO/IEC 18004): byte-mode segmentation with the four-bit
 * mode indicator and an 8- or 16-bit character count, the 0xEC/0x11 pad
 * sequence, Reed-Solomon over GF(256) with the 0x11D primitive, block splitting
 * and interleaving, the finder/separator/timing/alignment patterns, the dark
 * module, BCH(15,5) format information, BCH(18,6) version information for
 * version 7 and up, all eight data masks, and the four penalty rules used to
 * pick between them.
 *
 * HOW IT IS VERIFIED (tests/Auth/QrTest.php): every matrix it produces, for
 * every one of the eight masks, is compared module-for-module against the
 * `qrcode` npm package's output for the same input - the very encoder the
 * Next.js app used, captured into tests/Auth/fixtures/qr-reference.json. That
 * fixture is generated by Node on a development machine; the test itself needs
 * only PHP, so it also runs on the server.
 */
final class Qr
{
    /** Error correction level M: 2-bit spec value 00, and the level we encode at. */
    private const EC_LEVEL_BITS = 0b00;

    private const MIN_VERSION = 1;
    private const MAX_VERSION = 10;

    /** Total codewords (data + error correction) per version. ISO/IEC 18004 table 1. */
    private const TOTAL_CODEWORDS = [1 => 26, 44, 70, 100, 134, 172, 196, 242, 292, 346];

    /** Error-correction codewords for the WHOLE symbol at level M. */
    private const EC_CODEWORDS = [1 => 10, 16, 26, 36, 48, 64, 72, 88, 110, 130];

    /** Number of RS blocks at level M. */
    private const EC_BLOCKS = [1 => 1, 1, 1, 2, 2, 4, 4, 4, 5, 5];

    /** Alignment pattern centre coordinates. */
    private const ALIGNMENT = [
        1  => [],
        2  => [6, 18],
        3  => [6, 22],
        4  => [6, 26],
        5  => [6, 30],
        6  => [6, 34],
        7  => [6, 22, 38],
        8  => [6, 24, 42],
        9  => [6, 26, 46],
        10 => [6, 28, 50],
    ];

    /** Bits of padding after the interleaved codewords. */
    private const REMAINDER_BITS = [1 => 0, 7, 7, 7, 7, 7, 0, 0, 0, 0];

    private const MODE_BYTE = 0b0100;

    /** @var array<int,int>|null GF(256) antilog table, built once */
    private static ?array $exp = null;

    /** @var array<int,int>|null GF(256) log table */
    private static ?array $log = null;

    /**
     * @param list<list<bool>> $modules [row][col], true = dark
     */
    private function __construct(
        public readonly int $version,
        public readonly int $mask,
        private readonly array $modules,
    ) {
    }

    /** Modules per side, quiet zone excluded. */
    public function size(): int
    {
        return $this->version * 4 + 17;
    }

    public function isDark(int $row, int $col): bool
    {
        return $this->modules[$row][$col] ?? false;
    }

    /** @return list<list<bool>> */
    public function modules(): array
    {
        return $this->modules;
    }

    /** The largest byte string this encoder can hold. */
    public static function capacity(): int
    {
        return self::byteCapacity(self::MAX_VERSION);
    }

    /**
     * Encode, or throw if the text does not fit.
     *
     * @param int|null $forceMask 0-7 to pin the mask (the tests do); null picks
     *                            the least-penalised one, as the spec intends
     */
    public static function encode(string $text, ?int $forceMask = null): self
    {
        if ($text === '') {
            throw new AuthError('Nothing to encode in a QR code');
        }

        $version = self::versionFor(strlen($text));

        if ($version === null) {
            throw new AuthError(
                'Text is ' . strlen($text) . ' bytes; this encoder holds ' . self::capacity(),
                'That is too long to show as a QR code',
            );
        }

        $codewords = self::interleave($version, self::dataCodewords($version, $text));

        if ($forceMask !== null) {
            if ($forceMask < 0 || $forceMask > 7) {
                throw new AuthError('Mask must be 0-7');
            }

            return new self($version, $forceMask, self::build($version, $codewords, $forceMask));
        }

        $best      = null;
        $bestScore = PHP_INT_MAX;

        for ($mask = 0; $mask <= 7; $mask++) {
            $candidate = self::build($version, $codewords, $mask);
            $score     = self::penalty($candidate);

            if ($score < $bestScore) {
                $bestScore = $score;
                $best      = new self($version, $mask, $candidate);
            }
        }

        // Unreachable - the loop always runs - but the type says "self", so say so.
        return $best ?? throw new AuthError('No mask could be evaluated');
    }

    /** Encode, or null when it does not fit. For callers that have a text fallback ready. */
    public static function tryEncode(string $text, ?int $forceMask = null): ?self
    {
        try {
            return self::encode($text, $forceMask);
        } catch (AuthError) {
            return null;
        }
    }

    // ---------------------------------------------------------------- output

    /**
     * An SVG, as a string. Scales to whatever box it is put in, so the caller
     * does not have to guess a pixel size; `shape-rendering="crispEdges"` keeps
     * the modules square at any zoom, which is what a camera needs.
     *
     * @param int $quietZone modules of white margin. The spec says four and
     *                       scanners really do rely on it.
     */
    public function toSvg(int $quietZone = 4, string $dark = '#000000', string $light = '#ffffff'): string
    {
        $quietZone = max(0, min(16, $quietZone));
        $size      = $this->size();
        $side      = $size + $quietZone * 2;

        $path = '';

        for ($row = 0; $row < $size; $row++) {
            $col = 0;

            while ($col < $size) {
                if (!$this->modules[$row][$col]) {
                    $col++;

                    continue;
                }

                // Run-length: one <path> segment per horizontal run of dark
                // modules instead of one <rect> each. A version 10 code is
                // 2809 modules; the difference is a 4 KB image and a 40 KB one.
                $run = 0;

                while ($col + $run < $size && $this->modules[$row][$col + $run]) {
                    $run++;
                }

                $path .= 'M' . ($col + $quietZone) . ' ' . ($row + $quietZone) . 'h' . $run . 'v1h-' . $run . 'z';
                $col  += $run;
            }
        }

        return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' . $side . ' ' . $side . '"'
            . ' width="' . ($side * 4) . '" height="' . ($side * 4) . '"'
            . ' shape-rendering="crispEdges" role="img" aria-label="QR code">'
            . '<rect width="' . $side . '" height="' . $side . '" fill="' . self::colour($light) . '"/>'
            . '<path fill="' . self::colour($dark) . '" d="' . $path . '"/>'
            . '</svg>';
    }

    /** True when this host has GD, so toPngDataUri() will work. */
    public static function hasGd(): bool
    {
        return function_exists('imagecreatetruecolor') && function_exists('imagepng');
    }

    /**
     * A PNG data URI, the same shape TotpSetup.tsx already puts in an <img>
     * ("data:image/png;base64,..."), or null when the host has no GD - in which
     * case the caller shows the SVG or the text fallback.
     */
    public function toPngDataUri(int $moduleSize = 6, int $quietZone = 4): ?string
    {
        if (!self::hasGd()) {
            return null;
        }

        $moduleSize = max(1, min(20, $moduleSize));
        $quietZone  = max(0, min(16, $quietZone));
        $size       = $this->size();
        $pixels     = ($size + $quietZone * 2) * $moduleSize;

        $image = imagecreatetruecolor($pixels, $pixels);

        if ($image === false) {
            return null;
        }

        try {
            $white = (int) imagecolorallocate($image, 255, 255, 255);
            $black = (int) imagecolorallocate($image, 0, 0, 0);
            imagefilledrectangle($image, 0, 0, $pixels - 1, $pixels - 1, $white);

            for ($row = 0; $row < $size; $row++) {
                for ($col = 0; $col < $size; $col++) {
                    if (!$this->modules[$row][$col]) {
                        continue;
                    }

                    $x = ($col + $quietZone) * $moduleSize;
                    $y = ($row + $quietZone) * $moduleSize;
                    imagefilledrectangle($image, $x, $y, $x + $moduleSize - 1, $y + $moduleSize - 1, $black);
                }
            }

            ob_start();
            imagepng($image, null, 9);
            $png = (string) ob_get_clean();
        } finally {
            // Not imagedestroy(): it has done nothing since PHP 8.0 and 8.5
            // deprecates it. Dropping the reference frees the image.
            unset($image);
        }

        return $png === '' ? null : 'data:image/png;base64,' . base64_encode($png);
    }

    /**
     * The fallback when there is no QR at all: the secret in groups of four,
     * which is how every authenticator app's "enter a setup key" box expects
     * it, and the only thing on this page a person actually has to type.
     */
    public static function textFallback(string $secretBase32): string
    {
        return Totp::readable($secretBase32);
    }

    /** Modules as rows of "1" and "0" - the form the test compares. */
    public function toBitRows(): string
    {
        $out = '';

        foreach ($this->modules as $row) {
            foreach ($row as $module) {
                $out .= $module ? '1' : '0';
            }

            $out .= "\n";
        }

        return $out;
    }

    // --------------------------------------------------------------- encoding

    private static function dataCodewordCount(int $version): int
    {
        return self::TOTAL_CODEWORDS[$version] - self::EC_CODEWORDS[$version];
    }

    private static function charCountBits(int $version): int
    {
        // Byte mode: 8 bits up to version 9, 16 from version 10.
        return $version < 10 ? 8 : 16;
    }

    private static function byteCapacity(int $version): int
    {
        $bits = self::dataCodewordCount($version) * 8 - 4 - self::charCountBits($version);

        return intdiv($bits, 8);
    }

    private static function versionFor(int $length): ?int
    {
        for ($version = self::MIN_VERSION; $version <= self::MAX_VERSION; $version++) {
            if ($length <= self::byteCapacity($version)) {
                return $version;
            }
        }

        return null;
    }

    /**
     * Mode indicator, length, the bytes, a terminator, then 0xEC/0x11 until the
     * block is full.
     *
     * @return list<int>
     */
    private static function dataCodewords(int $version, string $text): array
    {
        $capacity = self::dataCodewordCount($version) * 8;
        $bits     = '';

        $bits .= str_pad(decbin(self::MODE_BYTE), 4, '0', STR_PAD_LEFT);
        $bits .= str_pad(decbin(strlen($text)), self::charCountBits($version), '0', STR_PAD_LEFT);

        for ($i = 0, $n = strlen($text); $i < $n; $i++) {
            $bits .= str_pad(decbin(ord($text[$i])), 8, '0', STR_PAD_LEFT);
        }

        // Terminator: up to four zero bits, fewer if the symbol is nearly full.
        $bits .= str_repeat('0', min(4, $capacity - strlen($bits)));

        // Then zeroes to the next byte boundary.
        if (strlen($bits) % 8 !== 0) {
            $bits .= str_repeat('0', 8 - strlen($bits) % 8);
        }

        $codewords = [];

        foreach (str_split($bits, 8) as $byte) {
            $codewords[] = (int) bindec($byte);
        }

        // The spec's pad bytes, alternating, to fill the data capacity.
        $pad = [0xEC, 0x11];

        for ($i = 0; count($codewords) < self::dataCodewordCount($version); $i++) {
            $codewords[] = $pad[$i % 2];
        }

        return $codewords;
    }

    /**
     * Split into RS blocks, add error correction, and interleave both halves.
     *
     * @param list<int> $data
     *
     * @return list<int>
     */
    private static function interleave(int $version, array $data): array
    {
        $blockCount = self::EC_BLOCKS[$version];
        $totalData  = self::dataCodewordCount($version);
        $ecPerBlock = intdiv(self::EC_CODEWORDS[$version], $blockCount);

        // The short blocks come first; the long ones hold one codeword more.
        $shortBlocks = $blockCount - ($totalData % $blockCount);
        $shortSize   = intdiv($totalData, $blockCount);

        $dataBlocks = [];
        $ecBlocks   = [];
        $offset     = 0;

        for ($i = 0; $i < $blockCount; $i++) {
            $size          = $i < $shortBlocks ? $shortSize : $shortSize + 1;
            $block         = array_slice($data, $offset, $size);
            $offset       += $size;
            $dataBlocks[]  = $block;
            $ecBlocks[]    = self::errorCorrection($block, $ecPerBlock);
        }

        $out = [];

        for ($i = 0; $i <= $shortSize; $i++) {
            foreach ($dataBlocks as $block) {
                if (isset($block[$i])) {
                    $out[] = $block[$i];
                }
            }
        }

        for ($i = 0; $i < $ecPerBlock; $i++) {
            foreach ($ecBlocks as $block) {
                $out[] = $block[$i];
            }
        }

        return $out;
    }

    // ------------------------------------------------------- GF(256) / Reed-Solomon

    private static function initGaloisField(): void
    {
        if (self::$exp !== null) {
            return;
        }

        $exp = array_fill(0, 512, 0);
        $log = array_fill(0, 256, 0);
        $x   = 1;

        for ($i = 0; $i < 255; $i++) {
            $exp[$i] = $x;
            $log[$x] = $i;
            $x     <<= 1;

            // x^8 + x^4 + x^3 + x^2 + 1, the QR primitive polynomial.
            if ($x & 0x100) {
                $x ^= 0x11D;
            }
        }

        for ($i = 255; $i < 512; $i++) {
            $exp[$i] = $exp[$i - 255];
        }

        self::$exp = $exp;
        self::$log = $log;
    }

    /**
     * The generator polynomial for n error-correction codewords:
     * (x - a^0)(x - a^1)...(x - a^(n-1)).
     *
     * @return list<int>
     */
    private static function generatorPolynomial(int $degree): array
    {
        self::initGaloisField();

        $poly = [1];

        for ($i = 0; $i < $degree; $i++) {
            $next = array_fill(0, count($poly) + 1, 0);

            foreach ($poly as $index => $coefficient) {
                $next[$index]     ^= $coefficient;
                $next[$index + 1] ^= self::multiply($coefficient, self::$exp[$i]);
            }

            $poly = $next;
        }

        return $poly;
    }

    private static function multiply(int $a, int $b): int
    {
        if ($a === 0 || $b === 0) {
            return 0;
        }

        return self::$exp[(self::$log[$a] + self::$log[$b]) % 255];
    }

    /**
     * Polynomial long division of the data by the generator; the remainder is
     * the error correction.
     *
     * @param list<int> $block
     *
     * @return list<int>
     */
    private static function errorCorrection(array $block, int $ecLength): array
    {
        self::initGaloisField();

        $generator = self::generatorPolynomial($ecLength);
        $remainder = array_merge($block, array_fill(0, $ecLength, 0));

        for ($i = 0, $n = count($block); $i < $n; $i++) {
            $factor = $remainder[$i];

            if ($factor === 0) {
                continue;
            }

            foreach ($generator as $index => $coefficient) {
                $remainder[$i + $index] ^= self::multiply($coefficient, $factor);
            }
        }

        return array_values(array_slice($remainder, count($block), $ecLength));
    }

    // ---------------------------------------------------------------- matrix

    /**
     * @param list<int> $codewords
     *
     * @return list<list<bool>>
     */
    private static function build(int $version, array $codewords, int $mask): array
    {
        $size     = $version * 4 + 17;
        $modules  = array_fill(0, $size, array_fill(0, $size, false));
        $reserved = array_fill(0, $size, array_fill(0, $size, false));

        self::placeFinders($modules, $reserved, $size);
        self::placeTiming($modules, $reserved, $size);
        self::placeAlignment($modules, $reserved, $version);
        self::reserveFormatAreas($reserved, $size);

        // The one module that is always dark, and is not part of any pattern.
        $modules[$size - 8][8]  = true;
        $reserved[$size - 8][8] = true;

        if ($version >= 7) {
            self::placeVersionInfo($modules, $reserved, $version, $size);
        }

        $placed = self::placeData($modules, $reserved, $codewords, $size, $mask);

        // The symbol must come out exactly full: every codeword bit placed,
        // plus the version's remainder bits and nothing else. If a table above
        // is ever edited wrongly this fires here, rather than producing a
        // plausible-looking code that no phone can read.
        $expected = count($codewords) * 8 + self::REMAINDER_BITS[$version];

        if ($placed !== $expected) {
            throw new AuthError('QR placement filled ' . $placed . ' bits, expected ' . $expected);
        }

        self::placeFormatInfo($modules, $mask, $size);

        return $modules;
    }

    /**
     * @param list<list<bool>> $modules
     * @param list<list<bool>> $reserved
     */
    private static function placeFinders(array &$modules, array &$reserved, int $size): void
    {
        foreach ([[0, 0], [0, $size - 7], [$size - 7, 0]] as [$top, $left]) {
            // The 7x7 finder plus its one-module separator: rows -1..7.
            for ($row = -1; $row <= 7; $row++) {
                for ($col = -1; $col <= 7; $col++) {
                    $r = $top + $row;
                    $c = $left + $col;

                    if ($r < 0 || $r >= $size || $c < 0 || $c >= $size) {
                        continue;
                    }

                    $inRing   = ($row === 0 || $row === 6) && $col >= 0 && $col <= 6;
                    $inColumn = ($col === 0 || $col === 6) && $row >= 0 && $row <= 6;
                    $inCore   = $row >= 2 && $row <= 4 && $col >= 2 && $col <= 4;

                    $modules[$r][$c]  = $inRing || $inColumn || $inCore;
                    $reserved[$r][$c] = true;
                }
            }
        }
    }

    /**
     * @param list<list<bool>> $modules
     * @param list<list<bool>> $reserved
     */
    private static function placeTiming(array &$modules, array &$reserved, int $size): void
    {
        for ($i = 8; $i < $size - 8; $i++) {
            $dark = $i % 2 === 0;

            $modules[6][$i]  = $dark;
            $reserved[6][$i] = true;
            $modules[$i][6]  = $dark;
            $reserved[$i][6] = true;
        }
    }

    /**
     * @param list<list<bool>> $modules
     * @param list<list<bool>> $reserved
     */
    private static function placeAlignment(array &$modules, array &$reserved, int $version): void
    {
        $centres = self::ALIGNMENT[$version];
        $last    = count($centres) - 1;

        foreach ($centres as $i => $row) {
            foreach ($centres as $j => $col) {
                // The three corners already hold finder patterns.
                if (($i === 0 && $j === 0) || ($i === 0 && $j === $last) || ($i === $last && $j === 0)) {
                    continue;
                }

                for ($dr = -2; $dr <= 2; $dr++) {
                    for ($dc = -2; $dc <= 2; $dc++) {
                        $modules[$row + $dr][$col + $dc]  = max(abs($dr), abs($dc)) !== 1;
                        $reserved[$row + $dr][$col + $dc] = true;
                    }
                }
            }
        }
    }

    /** @param list<list<bool>> $reserved */
    private static function reserveFormatAreas(array &$reserved, int $size): void
    {
        for ($i = 0; $i < 9; $i++) {
            $reserved[8][$i] = true;
            $reserved[$i][8] = true;
        }

        for ($i = 0; $i < 8; $i++) {
            $reserved[8][$size - 1 - $i] = true;
            $reserved[$size - 1 - $i][8] = true;
        }
    }

    /**
     * @param list<list<bool>> $modules
     * @param list<list<bool>> $reserved
     */
    private static function placeVersionInfo(array &$modules, array &$reserved, int $version, int $size): void
    {
        $bits = self::bch($version, 0x1F25, 12);

        for ($i = 0; $i < 18; $i++) {
            $bit = (($bits >> $i) & 1) === 1;
            $row = intdiv($i, 3);
            $col = $i % 3;

            $modules[$row][$size - 11 + $col]  = $bit;
            $reserved[$row][$size - 11 + $col] = true;
            $modules[$size - 11 + $col][$row]  = $bit;
            $reserved[$size - 11 + $col][$row] = true;
        }
    }

    /**
     * Zigzag placement: two-module-wide columns, right to left, alternating
     * upward and downward, skipping the vertical timing column at index 6.
     *
     * @param list<list<bool>> $modules
     * @param list<list<bool>> $reserved
     * @param list<int>        $codewords
     *
     * @return int how many modules were filled - checked by the caller
     */
    private static function placeData(array &$modules, array $reserved, array $codewords, int $size, int $mask): int
    {
        $bits = '';

        foreach ($codewords as $codeword) {
            $bits .= str_pad(decbin($codeword), 8, '0', STR_PAD_LEFT);
        }

        $index     = 0;
        $available = strlen($bits);
        $upward    = true;

        for ($right = $size - 1; $right > 0; $right -= 2) {
            if ($right === 6) {
                $right = 5; // Skip the timing column entirely.
            }

            for ($step = 0; $step < $size; $step++) {
                $row = $upward ? $size - 1 - $step : $step;

                for ($c = 0; $c < 2; $c++) {
                    $col = $right - $c;

                    if ($reserved[$row][$col]) {
                        continue;
                    }

                    // Past the end of the data come the remainder bits, which
                    // are zero before masking.
                    $dark = $index < $available && $bits[$index] === '1';
                    $index++;

                    $modules[$row][$col] = $dark !== self::maskAt($mask, $row, $col);
                }
            }

            $upward = !$upward;
        }

        return $index;
    }

    /** @param list<list<bool>> $modules */
    private static function placeFormatInfo(array &$modules, int $mask, int $size): void
    {
        // Five bits (EC level, then mask), BCH(15,5) with generator 0x537, then
        // XORed with 0x5412 so an all-zero format is not all-zero modules.
        $value = (self::EC_LEVEL_BITS << 3) | $mask;
        $bits  = (self::bch($value, 0x537, 10)) ^ 0x5412;

        for ($i = 0; $i < 15; $i++) {
            $bit = (($bits >> $i) & 1) === 1;

            // The copy beside the top-left finder, running down then right.
            if ($i < 6) {
                $modules[$i][8] = $bit;
            } elseif ($i < 8) {
                $modules[$i + 1][8] = $bit;
            } else {
                $modules[$size - 15 + $i][8] = $bit;
            }

            // The second copy, split between the top-right and bottom-left.
            if ($i < 8) {
                $modules[8][$size - 1 - $i] = $bit;
            } elseif ($i === 8) {
                $modules[8][7] = $bit;
            } else {
                $modules[8][15 - 1 - $i] = $bit;
            }
        }
    }

    /**
     * BCH remainder: shift the value up by $shift bits and reduce by the
     * generator. Used for both the format (15,5) and version (18,6) codes.
     */
    private static function bch(int $value, int $generator, int $shift): int
    {
        $remainder    = $value << $shift;
        $generatorTop = self::bitLength($generator);

        while (self::bitLength($remainder) >= $generatorTop) {
            $remainder ^= $generator << (self::bitLength($remainder) - $generatorTop);
        }

        return ($value << $shift) | $remainder;
    }

    private static function bitLength(int $value): int
    {
        $length = 0;

        while ($value !== 0) {
            $length++;
            $value >>= 1;
        }

        return $length;
    }

    private static function maskAt(int $mask, int $row, int $col): bool
    {
        return match ($mask) {
            0       => ($row + $col) % 2 === 0,
            1       => $row % 2 === 0,
            2       => $col % 3 === 0,
            3       => ($row + $col) % 3 === 0,
            4       => (intdiv($row, 2) + intdiv($col, 3)) % 2 === 0,
            5       => ($row * $col) % 2 + ($row * $col) % 3 === 0,
            6       => (($row * $col) % 2 + ($row * $col) % 3) % 2 === 0,
            7       => (($row + $col) % 2 + ($row * $col) % 3) % 2 === 0,
            default => throw new AuthError('Unknown mask ' . $mask),
        };
    }

    // --------------------------------------------------------------- penalty

    /**
     * The four penalty rules from the spec. Lower is better; the mask with the
     * lowest score is the one a scanner will have the easiest time with.
     *
     * @param list<list<bool>> $modules
     */
    private static function penalty(array $modules): int
    {
        $size  = count($modules);
        $score = 0;

        // Rule 1: runs of five or more of the same colour, each row and column.
        for ($i = 0; $i < $size; $i++) {
            foreach ([true, false] as $byRow) {
                $run  = 1;
                $last = null;

                for ($j = 0; $j < $size; $j++) {
                    $module = $byRow ? $modules[$i][$j] : $modules[$j][$i];

                    if ($module === $last) {
                        $run++;
                    } else {
                        if ($run >= 5) {
                            $score += 3 + ($run - 5);
                        }

                        $last = $module;
                        $run  = 1;
                    }
                }

                if ($run >= 5) {
                    $score += 3 + ($run - 5);
                }
            }
        }

        // Rule 2: every 2x2 block of one colour.
        for ($row = 0; $row < $size - 1; $row++) {
            for ($col = 0; $col < $size - 1; $col++) {
                $sum = (int) $modules[$row][$col] + (int) $modules[$row][$col + 1]
                    + (int) $modules[$row + 1][$col] + (int) $modules[$row + 1][$col + 1];

                if ($sum === 0 || $sum === 4) {
                    $score += 3;
                }
            }
        }

        // Rule 3: the finder-like 1:1:3:1:1 pattern with four light modules
        // beside it - the thing that makes a scanner think it found a corner.
        for ($i = 0; $i < $size; $i++) {
            $rowBits = 0;
            $colBits = 0;

            for ($j = 0; $j < $size; $j++) {
                $rowBits = (($rowBits << 1) & 0x7FF) | (int) $modules[$i][$j];
                $colBits = (($colBits << 1) & 0x7FF) | (int) $modules[$j][$i];

                if ($j >= 10) {
                    if ($rowBits === 0x5D0 || $rowBits === 0x05D) {
                        $score += 40;
                    }

                    if ($colBits === 0x5D0 || $colBits === 0x05D) {
                        $score += 40;
                    }
                }
            }
        }

        // Rule 4: how far the proportion of dark modules strays from half.
        $dark = 0;

        foreach ($modules as $row) {
            foreach ($row as $module) {
                $dark += $module ? 1 : 0;
            }
        }

        $total   = $size * $size;
        $percent = (int) (abs($dark * 100 / $total - 50) / 5);

        return $score + $percent * 10;
    }

    private static function colour(string $value): string
    {
        // Only hex colours reach the SVG, so nothing a caller passes can close
        // an attribute and open a script.
        return preg_match('/^#[0-9a-fA-F]{3,8}$/', $value) === 1 ? $value : '#000000';
    }
