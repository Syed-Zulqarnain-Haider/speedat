    /**
     * Declared last on purpose: the runner walks the methods in declaration
     * order, so by the time this runs every other method has recorded which
     * groups it checked. A group added to the vector file and to nothing else
     * would otherwise sit there looking like coverage.
     */
    public function testEveryGroupInTheVectorFileIsChecked(): void
    {
        $missed = [];

        foreach ($this->groups() as $group) {
            if (!isset(self::$ran[$group['fn']])) {
                $missed[] = $group['fn'];
            }
        }

        $this->assertSame([], $missed, 'these vector groups have no PHP handler: ' . implode(', ', $missed));
    }

    /* ------------------------------------------------------------ the runner */

    /**
     * Run every case of one group and assert each answer.
     *
     * @param \Closure(array<string,mixed>): mixed $actual
     */
    private function run(string $fn, \Closure $actual): void
    {
        $found = false;

        foreach ($this->groups() as $group) {
            if ($group['fn'] !== $fn) {
                continue;
            }

            $found              = true;
            self::$ran[$fn]     = true;

            foreach ($group['cases'] as $case) {
                /** @var array<string,mixed> $input */
                $input = $case['input'];
                $label = $fn . ' / ' . $case['name'];

                try {
                    $got = $actual($input);
                } catch (\Throwable $e) {
                    $this->fail($label . ' threw ' . $e::class . ': ' . $e->getMessage()
                        . ' (' . basename($e->getFile()) . ':' . $e->getLine() . ')');
                }

                $this->assertMatchesVector($case['expected'], $got, $label);
            }
        }

        if (!$found) {
            $this->fail('no vectors for ' . $fn . ' - regenerate tests/vectors/pricing.json');
        }
    }

    /**
     * Deep comparison against a decoded JSON value.
     *
     * Numbers are compared as numbers: the generator writes 8030 and PHP
     * computes 8030.0, and those are the same price. Everything else is
     * compared identically, so "1" never passes for 1.
     */
    private function assertMatchesVector(mixed $expected, mixed $actual, string $label): void
    {
        $problem = self::difference($expected, $actual, '');

        $this->assertTrue(
            $problem === null,
            $label . ($problem === null ? '' : ' - ' . $problem),
        );
    }

    /** @return string|null a description of the first difference, or null when they agree */
    private static function difference(mixed $expected, mixed $actual, string $path): ?string
    {
        $where = $path === '' ? '' : ' at ' . $path;

        if (is_array($expected)) {
            if (!is_array($actual)) {
                return 'expected an array' . $where . ', got ' . get_debug_type($actual);
            }

            if (count($expected) !== count($actual)) {
                return 'expected ' . count($expected) . ' entries' . $where . ', got ' . count($actual)
                    . ' (' . json_encode($actual, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . ')';
            }

            foreach ($expected as $key => $value) {
                if (!array_key_exists($key, $actual)) {
                    return 'missing key "' . $key . '"' . $where;
                }

                $problem = self::difference($value, $actual[$key], $path === '' ? (string) $key : $path . '.' . $key);
                if ($problem !== null) {
                    return $problem;
                }
            }

            return null;
        }

        if (is_int($expected) || is_float($expected)) {
            if (!is_int($actual) && !is_float($actual)) {
                return 'expected the number ' . $expected . $where . ', got ' . var_export($actual, true);
            }

            if (is_nan((float) $actual)) {
                return 'expected ' . $expected . $where . ', got NAN';
            }

            return (float) $expected === (float) $actual
                ? null
                : 'expected ' . var_export($expected, true) . $where . ', got ' . var_export($actual, true);
        }

        return $expected === $actual
            ? null
            : 'expected ' . var_export($expected, true) . $where . ', got ' . var_export($actual, true);
    }

    /* ------------------------------------------------- reading the vectors */

    /** @return array<string,mixed> */
    private function data(): array
    {
        if (self::$data === null) {
            $file = dirname(__DIR__) . '/tests/vectors/pricing.json';

            if (!is_file($file)) {
                $this->fail('tests/vectors/pricing.json is missing - regenerate it (see docs/engine-parity.md)');
            }

            $raw = file_get_contents($file);
            if ($raw === false) {
                $this->fail('tests/vectors/pricing.json could not be read');
            }

            /** @var array<string,mixed>|null $decoded */
            $decoded = json_decode($raw, true, 512, JSON_THROW_ON_ERROR);

            if (!is_array($decoded)) {
                $this->fail('tests/vectors/pricing.json is not a JSON object');
            }

            self::$data = $decoded;
        }

        return self::$data;
    }

    /** @return list<array{fn: string, cases: list<array{name: string, input: array<string,mixed>, expected: mixed}>}> */
    private function groups(): array
    {
        /** @var list<array{fn: string, cases: list<array{name: string, input: array<string,mixed>, expected: mixed}>}> $groups */
        $groups = $this->data()['groups'];

        return $groups;
    }

    private function site(string $name): SiteData
    {
        if (!isset(self::$siteCache[$name])) {
            /** @var array<string,array<string,mixed>> $sites */
            $sites = $this->data()['sites'];

            if (!isset($sites[$name])) {
                $this->fail('the vector file has no site called "' . $name . '"');
            }

            self::$siteCache[$name] = SiteData::fromArray($sites[$name]);
        }

        return self::$siteCache[$name];
    }

    private function card(string $name): RateCard
    {
        return $this->site($name)->card;
    }

    private function settings(string $name): Settings
    {
        return $this->site($name)->card->settings;
    }

    /**
     * @param  mixed $rows decoded JSON piece rows
     * @return list<Piece>
     */
    private function rows(mixed $rows): array
    {
        return is_array($rows) ? Piece::listFrom($rows) : [];
    }

    /* ------------------------------------------- shaping answers for compare */

    /** @return array<string,mixed> */
    private static function serialiseWeights(Weights $w): array
    {
        $lines = [];

        foreach ($w->lines as $line) {
            $lines[] = [
                'qty'            => $line->qty,
                'kg'             => self::finite($line->kg),
                'L'              => self::finite($line->L),
                'W'              => self::finite($line->W),
                'H'              => self::finite($line->H),
                'actualG'        => $line->actualG,
                'volG'           => $line->volG,
                'pieceG'         => $line->pieceG,
                'volumetricWins' => $line->volumetricWins,
            ];
        }

        return [
            'pieces'         => $w->pieces,
            'actualG'        => $w->actualG,
            'volG'           => $w->volG,
            'chargeG'        => $w->chargeG,
            'billableG'      => $w->billableG,
            'volumetricWins' => $w->volumetricWins,
            'lines'          => $lines,
        ];
    }

    /** @return array<string,mixed>|null */
    private static function serialisePrice(?ServicePrice $p): ?array
    {
        if ($p === null) {
            return null;
        }

        return [
            'first'  => self::finite($p->first),
            'addl'   => self::finite($p->addl),
            'steps'  => $p->steps,
            'gridKg' => $p->gridKg,
            'base'   => $p->base,
            'tax'    => $p->tax,
            'total'  => $p->total,
            'days'   => $p->days,
        ];
    }

    /** NAN is `undefined` on the other side, and JSON.stringify writes that as null. */
    private static function finite(?float $v): ?float
    {
        return $v === null || !is_finite($v) ? null : $v;
    }
}
