    /**
     * The same two functions again, with intl treated as missing.
     *
     * Hostinger may not have the extension, and an unfolded "ü" turns
     * "Türkiye" into the key "t rkiye" - which would quietly make the importer
     * create a second United Kingdom instead of updating the first. The
     * fallback table has to give the same answers as ICU, so it is checked
     * against the same vectors.
     */
    public function testAccentFoldingWithoutTheIntlExtension(): void
    {
        Str::withoutIntl(function (): void {
            $this->run('nameKey', fn (array $in): string => Format::nameKey($in['name'] === null ? null : (string) $in['name']));
            $this->run('slug', fn (array $in): string => Format::slug((string) $in['name']));
        });

        // Spot-check the letters that have NO canonical decomposition: the
        // table must leave them alone, because ICU does.
        Str::withoutIntl(function (): void {
            // A stroked O and an ash have no canonical decomposition, so ICU
            // leaves them and the a-z filter drops them. "OE" and "AE" would
            // be a transliteration, and would match the wrong destination.
            $this->assertSame('e', Str::nameKey("\u{00d8}E"));
            $this->assertSame('on', Str::nameKey("\u{00c6}on"));
            $this->assertSame('', Str::nameKey("\u{00df}"), 'a sharp s has no decomposition');
            $this->assertSame('turkiye', Str::nameKey("T\u{00fc}rkiye"));
            $this->assertSame('viet nam', Str::nameKey("Vi\u{1ec7}t Nam"));
        });
    }

