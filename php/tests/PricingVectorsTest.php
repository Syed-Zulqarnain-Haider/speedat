    public function testPrices(): void
    {
        $this->run('priceAll', function (array $in): array {
            /** @var array<string,mixed> $input */
            $input = $in['input'];
            $card  = $this->card((string) $in['site']);

            $result = Engine::priceAll(
                $card,
                (string) $input['destId'],
                $this->rows($input['rows']),
            );

            if (!$result->ok) {
                if ($result->reason !== 'overmax') {
                    return ['ok' => false, 'reason' => $result->reason];
                }

                return [
                    'ok'      => false,
                    'reason'  => $result->reason,
                    'destId'  => $result->dest?->id,
                    'weights' => self::serialiseWeights($result->weights ?? throw new \LogicException('overmax without weights')),
                ];
            }

            $prices = [];
            foreach ($result->prices as $serviceId => $price) {
                $prices[$serviceId] = self::serialisePrice($price);
            }

            return [
                'ok'      => true,
                'destId'  => $result->dest?->id,
                'weights' => self::serialiseWeights($result->weights ?? throw new \LogicException('priced without weights')),
                'prices'  => $prices,
            ];
        });
    }

